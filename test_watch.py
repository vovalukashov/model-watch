class TestChatgptPlans(unittest.TestCase):
    """chatgpt-plans: the PlanType union the Codex client generates from its Rust enum of ChatGPT plans."""

    FILE = ("// GENERATED CODE! DO NOT MODIFY BY HAND!\n\n// This file was generated by [ts-rs]"
            "(https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n\nexport type PlanType = {};\n")

    def plan_type_ts(self, *plans):
        return self.FILE.format(" | ".join(f'"{p}"' for p in plans))

    def source(self):
        return next(s for s in json.loads(watch.SOURCES.read_text(encoding="utf-8")) if s["name"] == "chatgpt-plans")

    def test_reads_every_plan_and_nothing_else(self):
        text = self.plan_type_ts("free", "plus", "pro", "prolite", "edu_plus", "unknown")
        self.assertEqual(watch.extract_ids(text.encode("utf-8"), self.source())[1],
                         ["edu_plus", "free", "plus", "pro", "prolite", "unknown"])

    def test_a_new_plan_is_news(self):
        # 25.09.2026 00:20 UTC: promax, a tier above Pro, landed in Codex two hours after it surfaced in chatgpt.com
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            (root / "data").mkdir()
            plans = root / "PlanType.ts"
            (root / "sources.json").write_text(json.dumps([{**self.source(), "url": plans.as_uri()}]), encoding="utf-8")

            def git(*args):
                subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", *args], cwd=root, check=True,
                               capture_output=True)

            def check(*names):
                plans.write_text(self.plan_type_ts(*names), encoding="utf-8")
                with quiet(), mock.patch.object(watch, "ROOT", root), mock.patch.object(watch, "DATA", root / "data"), \
                        mock.patch.object(watch, "SOURCES", root / "sources.json"), \
                        mock.patch.object(watch, "send_telegram") as send, \
                        mock.patch.object(watch, "ai_summary", return_value="OpenAI готовит тариф Pro Max.") as ai:
                    watch.main([])
                git("add", "-A")
                git("commit", "-qm", "snapshot")
                return send, ai

            git("init", "-q")
            send, _ = check("free", "plus", "pro", "prolite")
            send.assert_not_called()  # a source's first snapshot is not news
            send, ai = check("free", "plus", "pro", "prolite", "promax")
            self.assertEqual([n["name"] for n in ai.call_args[0][0]["novel"]], ["promax"])
            self.assertIn("+ promax 🆕", send.call_args[0][0])


