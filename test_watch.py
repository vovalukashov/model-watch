class TestApify(unittest.TestCase):
    SRC = {"name": "chatgpt-web", "kind": "apify", "url": "https://chatgpt.com/", "token": "${APIFY_TOKEN}",
           "extract": "key_list", "key": "matches", "pattern": r"\b(gpt-[\w.\-]+)", "min_interval_hours": 6}
    NOW = "2026-09-25T12:00Z"

    def due(self, state=None, hours=6):
        with tempfile.TemporaryDirectory() as d:
            data = Path(d)
            if state is not None:
                (data / "chatgpt-web.apify-state.json").write_text(json.dumps(state), encoding="utf-8")
            with mock.patch.object(watch, "DATA", data):
                return watch.apify_due({**self.SRC, "min_interval_hours": hours}, at(self.NOW))

    def test_due_without_a_state_file(self):
        self.assertTrue(self.due())

    def test_not_due_right_after_a_run(self):
        self.assertFalse(self.due({"last_run": "2026-09-25T09:00Z"}))

    def test_due_once_the_interval_has_passed(self):
        self.assertTrue(self.due({"last_run": "2026-09-25T05:59Z"}))

    def test_a_broken_state_file_means_due(self):
        self.assertTrue(self.due({}))

    def test_run_builds_the_actor_call_and_packs_matches(self):
        items = [{"url": "https://chatgpt.com/", "scripts": 12, "fetched": 11, "blocked": 1,
                  "matches": ["gpt-6-sol", "GPT-5.5"]},
                 {"url": "https://chatgpt.com/", "scripts": 12, "fetched": 12, "blocked": 0,
                  "matches": ["o4-mini"]}]
        reply = mock.MagicMock()
        reply.__enter__.return_value.read.return_value = json.dumps(items).encode("utf-8")
        with mock.patch.object(watch.urllib.request, "urlopen", return_value=reply) as urlopen:
            raw = watch.apify_run(self.SRC, "apify-token")
        req = urlopen.call_args[0][0]
        self.assertTrue(req.full_url.startswith(
            "https://api.apify.com/v2/acts/apify~playwright-scraper/run-sync-get-dataset-items?"))
        self.assertIn("token=apify-token", req.full_url)
        body = json.loads(req.data.decode("utf-8"))
        self.assertEqual(body["startUrls"], [{"url": "https://chatgpt.com/"}])
        self.assertEqual(body["proxyConfiguration"]["apifyProxyGroups"], ["RESIDENTIAL"])
        self.assertIn(json.dumps(self.SRC["pattern"]), body["pageFunction"])  # the site's regex, JSON-escaped
        self.assertIn("'gi'", body["pageFunction"])
        snapshot = json.loads(raw.decode("utf-8"))
        self.assertEqual(snapshot["matches"], ["GPT-5.5", "gpt-6-sol", "o4-mini"])
        self.assertEqual(snapshot["pages"][0]["blocked"], 1)
        _, ids, _ = watch.extract_ids(raw, {**self.SRC, "lowercase": True})
        self.assertEqual(ids, ["gpt-5.5", "gpt-6-sol", "o4-mini"])

    def test_fetch_source_skips_without_a_token(self):
        with mock.patch.dict("os.environ", {}, clear=True), quiet():
            self.assertIsNone(watch.fetch_source(self.SRC, {}, at(self.NOW)))

    def test_fetch_source_skips_inside_the_interval(self):
        with tempfile.TemporaryDirectory() as d:
            (Path(d) / "chatgpt-web.apify-state.json").write_text('{"last_run": "2026-09-25T11:30Z"}\n',
                                                                  encoding="utf-8")
            with mock.patch.dict("os.environ", {"APIFY_TOKEN": "t"}, clear=True), \
                    mock.patch.object(watch, "DATA", Path(d)), quiet(), \
                    mock.patch.object(watch, "apify_run") as run:
                self.assertIsNone(watch.fetch_source(self.SRC, {}, at(self.NOW)))
        run.assert_not_called()

    def test_fetch_source_runs_the_actor_and_marks_the_state(self):
        with tempfile.TemporaryDirectory() as d:
            with mock.patch.dict("os.environ", {"APIFY_TOKEN": "t"}, clear=True), \
                    mock.patch.object(watch, "DATA", Path(d)), quiet(), \
                    mock.patch.object(watch, "apify_run", return_value=b'{"matches": []}') as run:
                self.assertEqual(watch.fetch_source(self.SRC, {}, at(self.NOW)), b'{"matches": []}')
            run.assert_called_once_with(self.SRC, "t")
            state = json.loads((Path(d) / "chatgpt-web.apify-state.json").read_text(encoding="utf-8"))
            self.assertEqual(state["last_run"], self.NOW)

    def test_a_failed_run_still_marks_the_state(self):
        # a failed actor run cost money too; the interval caps retries the same way
        with tempfile.TemporaryDirectory() as d:
            with mock.patch.dict("os.environ", {"APIFY_TOKEN": "t"}, clear=True), \
                    mock.patch.object(watch, "DATA", Path(d)), quiet(), \
                    mock.patch.object(watch, "apify_run",
                                      side_effect=watch.urllib.error.URLError("payment required")):
                with self.assertRaises(watch.urllib.error.URLError):
                    watch.fetch_source(self.SRC, {}, at(self.NOW))
                self.assertFalse(watch.apify_due(self.SRC, at("2026-09-25T13:00Z")))

    def test_plain_sources_go_through_fetch(self):
        with mock.patch.object(watch, "fetch", return_value=b"{}") as f:
            out = watch.fetch_source({"name": "x", "url": "https://x"}, {"A": "b"}, at(self.NOW))
        self.assertEqual(out, b"{}")
        f.assert_called_once_with("https://x", {"A": "b"})

    def test_apify_patterns_are_js_regexes(self):
        # the page function compiles them with new RegExp(pattern, 'gi'): inline flag groups like (?i) break
        # that, while (?:...), (?=...) and (?!...) are fine
        import re
        for src in json.loads(watch.SOURCES.read_text(encoding="utf-8")):
            if src.get("kind") == "apify":
                with self.subTest(source=src["name"]):
                    self.assertIsNone(re.search(r"\(\?[a-z]", src["pattern"]))

    def test_http_error_carries_apifys_message(self):
        err = watch.urllib.error.HTTPError("https://api.apify.com/x", 400, "Bad Request", {},
                                           io.BytesIO(b'{"error":{"message":"bad input"}}'))
        with mock.patch.object(watch.urllib.request, "urlopen", side_effect=err), quiet():
            with self.assertRaises(ValueError) as ctx:
                watch.apify_run(self.SRC, "t")
        self.assertIn("bad input", str(ctx.exception))


class TestWebSourcePatterns(unittest.TestCase):
    """The real chatgpt-web/claude-web patterns against strings the first chatgpt.com snapshot brought."""

    def matches(self, name, text):
        src = next(s for s in json.loads(watch.SOURCES.read_text(encoding="utf-8")) if s["name"] == name)
        # the actor's RegExp runs with the i flag while extract_ids compiles without flags,
        # so feed the text already lowercased — same matches for these patterns
        return watch.extract_ids(text.lower().encode("utf-8"),
                                 {**src, "kind": "text", "extract": "regex"})[1]

    def test_chatgpt_web_keeps_models_and_drops_ui_noise(self):
        ids = self.matches("chatgpt-web",
                           "GPT-5.2.instant.access gpt-6-sol GPT-Live-1 o4-mini GPT-4. "
                           "chatgpt-dv4fkqfn.js codex-canva codex-chatgpt-version-imoe7dyk.js")
        self.assertEqual(ids, ["gpt-4", "gpt-5.2.instant.access", "gpt-6-sol", "gpt-live-1", "o4-mini"])

    def test_chatgpt_web_catches_plan_rollout_strings(self):
        # how a new plan shows up in the bundle: subscription UI strings and planType comparisons —
        # promax surfaced in chatgpt.com's code two hours before PlanType.ts
        ids = self.matches("chatgpt-web",
                           'chatgpt-subscription-complete-pro-max chatgpt-promax-intent-to-pay '
                           'planType:"promax" plan_type="go" "plans.prolite" '
                           '"chatgpt-free-plan" plans are great plan.id')
        self.assertEqual(ids, ["chatgpt-free-plan", "chatgpt-promax-intent-to-pay",
                               "chatgpt-subscription-complete-pro-max", "go", "id", "prolite", "promax"])

    def test_claude_web_keeps_model_ids_and_drops_assets(self):
        ids = self.matches("claude-web",
                           'claude-opus-5-5 claude_wafer_eap Claude-Haiku-4-5 claude.ai claude-app '
                           'claude-main-a1b2c3.js claude-icon.webp planType:"ultra"')
        self.assertEqual(ids, ["claude-app", "claude-haiku-4-5", "claude-opus-5-5", "claude_wafer_eap", "ultra"])

    def test_regex_extract_takes_the_first_matched_group(self):
        # a multi-group pattern used to put None into the id list for matches outside group 1
        src = {"kind": "text", "extract": "regex", "pattern": r"(?:foo-(\w+)|bar-(\w+))"}
        self.assertEqual(watch.extract_ids(b"foo-one bar-two", src)[1], ["one", "two"])

    def test_exclude_drops_asset_filenames(self):
        src = {"kind": "text", "extract": "regex", "pattern": r"\b(gpt-[\w.\-]+)", "exclude": r"\.js$"}
        self.assertEqual(watch.extract_ids(b"gpt-5 gpt-chunk-a1b2.js", src)[1], ["gpt-5"])


class TestSummarize(unittest.TestCase):
    def test_picks_price_and_context(self):
        entry = {"cost": {"input": 2.5, "output": 10}, "limit": {"context": 400000}, "name": "GPT-6 Sol"}
        out = watch.summarize(entry)
        self.assertIn("cost.input=2.5", out)
        self.assertIn("limit.context=400000", out)
        self.assertNotIn("name=", out)

    def test_picks_litellm_field_names(self):
        entry = {"input_cost_per_token": 2.5e-06, "max_input_tokens": 400000, "litellm_provider": "openai"}
        out = watch.summarize(entry)
        self.assertIn("input_cost_per_token=2.5e-06", out)
        self.assertIn("max_input_tokens=400000", out)

    def test_truncates_to_budget(self):
        entry = {f"cost_{i}": i for i in range(100)}
        out = watch.summarize(entry, budget=80)
        self.assertLessEqual(len(out), 80)

    def test_cache_fields_go_last(self):
        entry = {
            "cache_read_input_token_cost": 1.5e-06,
            "input_cost_per_token": 1.5e-05,
            "output_cost_per_token": 7.5e-05,
        }
        out = watch.summarize(entry)
        self.assertLess(out.index("input_cost_per_token="), out.index("cache_read_input_token_cost="))
        self.assertLess(out.index("output_cost_per_token="), out.index("cache_read_input_token_cost="))

    def test_entry_without_interesting_fields(self):
        self.assertEqual(watch.summarize({"name": "x", "owner": "y"}), "")

    def test_non_dict_entry(self):
        self.assertEqual(watch.summarize(None), "")
        self.assertEqual(watch.summarize("gpt-6-sol"), "")


class TestFormatChange(unittest.TestCase):
    def test_added_id_carries_details(self):
        parsed = {"gpt-6-sol": {"input_cost_per_token": 2.5e-06, "max_input_tokens": 400000}}
        src = {"name": "litellm-prices", "url": "https://example/x.json", "extract": "top_keys"}
        out = watch.format_change(src, ["gpt-6-sol"], [], parsed)
        self.assertIn("• litellm-prices", out)
        self.assertIn("+ gpt-6-sol", out)
        self.assertIn("max_input_tokens=400000", out)

    def test_removed_id_stays_plain(self):
        src = {"name": "openrouter", "url": "https://example/y"}
        out = watch.format_change(src, [], ["old-model"], None)
        self.assertIn("− old-model", out)
        self.assertNotIn("+", out.split("\n", 1)[1])

    def test_details_only_for_first_few(self):
        parsed = {f"gpt-{i}": {"max_input_tokens": 1000 + i} for i in range(watch.DETAIL_LIMIT + 3)}
        src = {"name": "n", "url": "u", "extract": "top_keys"}
        out = watch.format_change(src, sorted(parsed), [], parsed)
        self.assertEqual(out.count("max_input_tokens="), watch.DETAIL_LIMIT)

    def test_unknown_id_degrades_to_bare_line(self):
        src = {"name": "n", "url": "u", "extract": "top_keys"}
        out = watch.format_change(src, ["ghost"], [], {})
        self.assertIn("+ ghost", out)

    def test_novel_id_is_marked(self):
        src = {"name": "openrouter", "url": "u"}
        out = watch.format_change(src, ["openai/gpt-6-sol", "openai/gpt-5"], [], None, novel={"openai/gpt-6-sol"})
        self.assertIn("+ openai/gpt-6-sol 🆕", out)
        self.assertNotIn("gpt-5 🆕", out)

    def test_long_removal_list_is_collapsed(self):
        src = {"name": "litellm-prices", "url": "u"}
        removed = [f"old-{i:03d}" for i in range(watch.REMOVED_LIMIT + 136)]
        out = watch.format_change(src, [], removed, None)
        self.assertEqual(out.count("− old-"), watch.REMOVED_LIMIT)
        self.assertIn("… ещё 136", out)


