class TestMainEndToEnd(unittest.TestCase):
    """Runs main() against a throwaway git repo with file:// sources: the real fetch → diff → message path."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        root = Path(self.tmp.name)
        (root / "data").mkdir()
        self.catalog = root / "catalog.json"
        self.prices = root / "prices.json"
        sources = [
            {"name": "catalog-a", "url": self.catalog.as_uri(), "kind": "json", "extract": "key", "key": "id"},
            {"name": "prices-b", "url": self.prices.as_uri(), "kind": "json", "extract": "top_keys"},
        ]
        (root / "sources.json").write_text(json.dumps(sources), encoding="utf-8")
        (root / "data" / "catalog-a.ids.txt").write_text("gpt-5\n", encoding="utf-8")
        (root / "data" / "prices-b.ids.txt").write_text("claude-opus-4-8\n", encoding="utf-8")
        for args in (["init", "-q"], ["add", "-A"],
                     ["-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "-m", "base"]):
            subprocess.run(["git", *args], cwd=root, check=True)
        self.patches = [mock.patch.object(watch, "ROOT", root), mock.patch.object(watch, "DATA", root / "data"),
                        mock.patch.object(watch, "SOURCES", root / "sources.json")]
        for p in self.patches:
            p.start()

    def tearDown(self):
        for p in self.patches:
            p.stop()
        self.tmp.cleanup()

    def run_main(self, catalog, prices):
        self.catalog.write_text(json.dumps(catalog), encoding="utf-8")
        self.prices.write_text(json.dumps(prices), encoding="utf-8")
        out = io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(io.StringIO()), \
                mock.patch.object(watch, "send_telegram") as send, \
                mock.patch.object(watch, "ai_summary", return_value="Похоже на релиз GPT-6.") as ai:
            watch.main([])
        self.log = out.getvalue()
        return send, ai

    def test_new_model_gets_an_ai_summary_and_an_alert(self):
        send, ai = self.run_main(
            {"data": [{"id": "gpt-5"}, {"id": "gpt-6-sol", "limit": {"context": 1000000}}]},
            {"claude-opus-4-8": {}, "azure/gpt-5": {"max_input_tokens": 400000}},
        )
        payload = ai.call_args[0][0]
        self.assertEqual([n["name"] for n in payload["novel"]], ["gpt-6-sol"])
        self.assertEqual(payload["novel"][0]["seen_in"][0]["details"], "limit.context=1000000")
        send.assert_called_once()
        text = send.call_args[0][0]
        self.assertTrue(text.startswith("model-watch: 🆕"))
        self.assertIn("Похоже на релиз GPT-6.", text)
        self.assertIn("+ gpt-6-sol 🆕", text)
        self.assertIn("+ azure/gpt-5\n", text + "\n")
        self.assertNotIn("azure/gpt-5 🆕", text)

    def test_known_models_in_new_places_stay_in_the_log(self):
        send, ai = self.run_main(
            {"data": [{"id": "gpt-5"}]},
            {"claude-opus-4-8": {}, "azure/gpt-5": {}, "bedrock/us.anthropic.claude-opus-4-8": {}},
        )
        ai.assert_not_called()
        send.assert_not_called()
        self.assertIn("model-watch: новых моделей нет", self.log)
        self.assertIn("+ azure/gpt-5", self.log)

    def test_no_changes_send_nothing(self):
        send, ai = self.run_main({"data": [{"id": "gpt-5"}]}, {"claude-opus-4-8": {}})
        send.assert_not_called()
        ai.assert_not_called()

    def test_a_regular_check_leaves_the_chain_to_its_own_step(self):
        env = {"GITHUB_EVENT_NAME": "schedule", "GITHUB_REPOSITORY": "vova/model-watch"}
        with mock.patch.dict("os.environ", env), mock.patch.object(watch, "chain_warning") as check:
            self.run_main({"data": [{"id": "gpt-5"}]}, {"claude-opus-4-8": {}})
        check.assert_not_called()


class TestLeakDay(unittest.TestCase):
    """A leak day through main(), shaped like 22.09.2026: a catalog lists two unreleased names, drops both two hours
    later and brings one of them back at launch; the other never returns."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = root = Path(self.tmp.name)
        (root / "data").mkdir()
        self.azure = root / "azure.json"
        self.feed = root / "feed.txt"
        sources = [
            {"name": "azure", "url": self.azure.as_uri(), "kind": "json", "extract": "key", "key": "id"},
            {"name": "feed", "url": self.feed.as_uri(), "kind": "text", "extract": "regex",
             "pattern": r"\b((?:gpt|codex)-[\w.\-]+)", "alert_removed": False},
        ]
        (root / "sources.json").write_text(json.dumps(sources), encoding="utf-8")
        (root / "data" / "azure.ids.txt").write_text("gpt-5\n", encoding="utf-8")
        (root / "data" / "feed.ids.txt").write_text("", encoding="utf-8")
        self.git("init", "-q")
        self.commit()
        self.patches = [mock.patch.object(watch, "ROOT", root), mock.patch.object(watch, "DATA", root / "data"),
                        mock.patch.object(watch, "SOURCES", root / "sources.json")]
        for p in self.patches:
            p.start()

    def tearDown(self):
        for p in self.patches:
            p.stop()
        self.tmp.cleanup()

    def git(self, *args):
        subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", *args], cwd=self.root,
                       check=False, capture_output=True)

    def commit(self):  # what the workflow's "Commit snapshot" step does after every check
        self.git("add", "-A")
        self.git("commit", "-q", "-m", "snapshot")

    def check(self, stamp, azure_ids, feed_text=""):
        self.azure.write_text(json.dumps({"data": [{"id": i} for i in azure_ids]}), encoding="utf-8")
        self.feed.write_text(feed_text, encoding="utf-8")
        with quiet(), mock.patch.object(watch, "utc_now", return_value=at(stamp)), \
                mock.patch.object(watch, "send_telegram") as send, \
                mock.patch.object(watch, "ai_summary", return_value="Похоже на слив GPT-6.") as ai:
            watch.main([])
        self.commit()
        return send, ai

    def test_leak_pulled_then_released(self):
        send, ai = self.check("2026-09-22T13:10Z", ["gpt-5", "gpt-6-sol", "gpt-6-astra-minor"])
        self.assertEqual({n["name"] for n in ai.call_args[0][0]["novel"]}, {"gpt-6-sol", "gpt-6-astra-minor"})
        self.assertTrue(send.call_args[0][0].startswith("model-watch: 🆕"))

        send, ai = self.check("2026-09-22T15:27Z", ["gpt-5"])
        ai.assert_not_called()
        text = send.call_args[0][0]
        send.assert_called_once()
        self.assertTrue(text.startswith("model-watch: 🫥"))
        self.assertIn("🫥 убрали: gpt-6-astra-minor из azure — появилось 22.09 13:10 UTC, больше ни в одном каталоге",
                      text)
        self.assertIn("🫥 убрали: gpt-6-sol из azure — появилось 22.09 13:10 UTC", text)

        send, ai = self.check("2026-09-22T18:59Z", ["gpt-5", "gpt-6-sol"])
        ai.assert_not_called()  # not novel any more: the memory kept it after Azure dropped it
        text = send.call_args[0][0]
        send.assert_called_once()
        self.assertTrue(text.startswith("model-watch: ↩️"))
        self.assertIn("↩️ вернулось: gpt-6-sol — снова в azure", text)
        self.assertNotIn("🆕", text)

        seen = watch.load_seen(self.root / "data")
        self.assertEqual(seen["gpt-6-astra-minor"],  # still waiting to come back
                         {"first_seen": "2026-09-22T13:10Z", "catalog": True, "pulled": "2026-09-22T15:27Z"})
        self.assertEqual(seen["gpt-6-sol"]["pulled"], "")
        self.assertEqual(seen["gpt-5"], {"first_seen": "", "catalog": True, "pulled": ""})  # there before the memory

    def test_a_name_scrolling_back_into_a_commit_feed_is_not_new(self):
        send, _ = self.check("2026-09-22T18:59Z", ["gpt-5"], "bump codex-rs")
        self.assertTrue(send.call_args[0][0].startswith("model-watch: 🆕"))  # first sighting ever is news

        send, _ = self.check("2026-09-23T00:20Z", ["gpt-5"], "docs only")
        send.assert_not_called()  # leaving a rolling feed is not an event

        send, ai = self.check("2026-09-23T12:04Z", ["gpt-5"], "bump codex-rs again")
        ai.assert_not_called()
        send.assert_not_called()  # already known: it stays in the log

    def test_a_model_that_leaves_after_a_week_and_comes_back_is_routine(self):
        self.check("2026-09-22T13:10Z", ["gpt-5", "grok-3-beta"])
        send, _ = self.check("2026-09-30T09:00Z", ["gpt-5"])
        send.assert_not_called()  # a cleanup, not a pulled leak
        send, ai = self.check("2026-10-01T09:00Z", ["gpt-5", "grok-3-beta"])
        ai.assert_not_called()
        send.assert_not_called()  # a revert, not a return

    def test_a_name_a_commit_feed_leaked_is_news_when_a_catalog_lists_it(self):
        self.check("2026-09-22T18:59Z", ["gpt-5"], "route gpt-7 behind a flag")
        self.check("2026-09-23T09:00Z", ["gpt-5"], "docs only")  # the feed scrolled past it
        send, ai = self.check("2026-09-25T18:00Z", ["gpt-5", "gpt-7"], "docs only")
        self.assertEqual([n["name"] for n in ai.call_args[0][0]["novel"]], ["gpt-7"])
        send.assert_called_once()
        self.assertTrue(send.call_args[0][0].startswith("model-watch: 🆕"))

    def test_a_catalog_listing_is_news_while_the_feed_still_mentions_the_name(self):
        self.check("2026-09-22T18:59Z", ["gpt-5"], "route gpt-7 behind a flag")
        send, ai = self.check("2026-09-22T21:59Z", ["gpt-5", "gpt-7"], "route gpt-7 behind a flag")
        self.assertEqual([n["name"] for n in ai.call_args[0][0]["novel"]], ["gpt-7"])
        send.assert_called_once()

    def test_names_the_memory_missed_are_kept_when_they_leave(self):
        # seen.tsv was seeded before the last snapshot, which brought gemini-x; the next check drops it again
        data = self.root / "data"
        watch.save_seen(data, {"gpt-5": {"first_seen": "", "catalog": True, "pulled": ""}})
        (data / "azure.ids.txt").write_text("gemini-x\ngpt-5\n", encoding="utf-8")
        self.commit()
        self.check("2026-09-23T17:00Z", ["gpt-5"])
        self.assertEqual(watch.load_seen(data)["gemini-x"], {"first_seen": "", "catalog": True, "pulled": ""})

    def test_first_check_starts_the_memory_quietly(self):
        send, _ = self.check("2026-09-22T13:10Z", ["gpt-5"])
        send.assert_not_called()
        self.assertEqual(watch.load_seen(self.root / "data"), {"gpt-5": {"first_seen": "", "catalog": True, "pulled": ""}})


